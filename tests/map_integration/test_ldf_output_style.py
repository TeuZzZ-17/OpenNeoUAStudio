"""Readable output preserves map data and the editor's restoration history."""
from map_editor.core.ldf_model import LdfDocument, dumps_ldf, loads_ldf, ensure_host_defaults
from map_editor.core.special_objects import add_special, update_special, remove_special


def test_coordinates_are_short_and_stable_without_changing_the_open_document():
    doc = LdfDocument(mw=24, mh=24)
    doc.newline = '\n'
    doc.squads = [dict(owner=4, veh=33, num=4, x=7, y=11, hidden=False,
                       useable=True, custom_name=None,
                       pos_x=9049.7000000000007, pos_z=-13800.299999999999)]
    host = dict(owner=1, veh=56, x=3, y=3, pos_x=4201.123456789012,
                pos_z=-4202.987654321012, pos_y=-0.00000000001,
                energy=500000, hidden=False, custom_name=None)
    ensure_host_defaults(host)
    doc.host_stations = [host]
    original_x = host['pos_x']
    text = dumps_ldf(doc)
    assert 'pos_x = 9049.7' in text and 'pos_z = -13800.3' in text
    assert 'pos_x = 4201.12346' in text and 'pos_z = -4202.98765' in text
    assert 'pos_y = 0\n' in text
    assert host['pos_x'] == original_x
    assert 'vehicle = 33 ;' not in text
    assert dumps_ldf(loads_ldf(text)) == text


def test_editor_backups_are_in_a_footer_and_still_restore_after_reopen():
    doc = LdfDocument(mw=9, mh=9)
    doc.newline = '\n'
    doc.grids['type'][3][3] = '1b'
    doc.remember_building_ground(3, 3, 8)
    doc.grids['type'][3][3], doc.grids['blg'][3][3] = '08', '08'
    doc.grids['type'][4][4] = 'a1'
    gate = add_special(doc, 'gate')
    update_special(doc, 'gate', gate, dict(x=4, y=4))
    text = dumps_ldf(doc)
    assert text.startswith('; --- Generated by OpenNeoUA Studio ---\n')
    assert text.index('Studio building ground') > text.index('begin_maps')
    assert text.index('Studio special ground') > text.index('begin_maps')
    assert 'Editor data' in text
    restored = loads_ldf(text)
    assert not restored.script_content.strip()
    assert dumps_ldf(restored) == text
    restored.remove_building(3, 3)
    remove_special(restored, 'gate', gate)
    assert restored.grids['type'][3][3] == '1b'
    assert restored.grids['type'][4][4] == 'a1'


def test_old_header_backups_are_still_loaded_and_resaved_in_the_footer():
    doc = LdfDocument(mw=9, mh=9)
    doc.grids['type'][3][3], doc.grids['blg'][3][3] = '08', '08'
    text = dumps_ldf(doc)
    text = '; Studio building ground 3 3 1b 08\n' + text
    restored = loads_ldf(text)
    assert restored.building_underlays[3, 3] == ('1b', '08')
    output = dumps_ldf(restored)
    assert output.index('Studio building ground') > output.index('begin_maps')


def test_clean_output_preserves_windows_newlines_and_named_definition_comments():
    doc = LdfDocument(mw=9, mh=9)
    doc.newline = '\r\n'
    doc.tech[1]['veh'] = [1]
    doc.tech[1]['blg'] = [8]
    text = dumps_ldf(doc, {'veh': {1: 'Weasel'}, 'blg': {8: 'Flak'}})
    assert '\n' not in text.replace('\r\n', '')
    assert 'vehicle = 1 ; Weasel\r\n' in text
    assert 'building = 8 ; Flak\r\n' in text
